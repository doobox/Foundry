import Foundation

nonisolated struct BlockInspectorControlGroup: Identifiable {
    let id: BlockProperty.Key
    var properties: [BlockPropertyDefinition]

    static func groups(for properties: [BlockPropertyDefinition]) -> [Self] {
        var groups: [Self] = []
        for property in properties {
            if let controlID = property.inspectorControlID,
               let last = groups.last,
               last.properties.last?.inspectorControlID == controlID {
                groups[groups.count - 1].properties.append(property)
            } else {
                groups.append(Self(id: property.key, properties: [property]))
            }
        }
        return groups
    }
}

nonisolated struct BlockDefinition: Sendable {
    static let genericSystemImage = "square.stack.3d.up"

    let type: BlockType
    let displayName: String
    let systemImage: String
    let category: BlockCategory
    let allowsChildren: Bool
    let renderKind: BlockRenderKind
    let properties: [BlockPropertyDefinition]
    let package: LoadedBlockPackage?

    init(
        type: BlockType,
        displayName: String,
        systemImage: String,
        category: BlockCategory,
        allowsChildren: Bool,
        renderKind: BlockRenderKind,
        properties: [BlockPropertyDefinition],
        package: LoadedBlockPackage? = nil
    ) {
        self.type = type
        self.displayName = displayName
        self.systemImage = systemImage
        self.category = category
        self.allowsChildren = allowsChildren
        self.renderKind = renderKind
        self.properties = properties
        self.package = package
    }
}

nonisolated struct BlockCategory: RawRepresentable, Hashable, Sendable {
    let rawValue: String

    init(rawValue: String) {
        self.rawValue = rawValue
    }

    static let layout = BlockCategory(rawValue: "Layout")
    static let content = BlockCategory(rawValue: "Content")
    static let media = BlockCategory(rawValue: "Media")
    static let navigation = BlockCategory(rawValue: "Navigation")
    static let forms = BlockCategory(rawValue: "Forms")
    static let interactive = BlockCategory(rawValue: "Interactive")
    static let other = BlockCategory(rawValue: "Other")
    static let unavailable = other
}

nonisolated enum BlockPackageGroup: String, CaseIterable, Sendable {
    case layout = "Layout"
    case content = "Content"
    case media = "Media"
    case navigation = "Navigation"
    case forms = "Forms"
    case interactive = "Interactive"
    case other = "Other"

    static func resolve(_ value: String) -> BlockPackageGroup {
        allCases.first { $0.rawValue.caseInsensitiveCompare(value) == .orderedSame } ?? .other
    }
}

nonisolated enum BlockRenderKind: Sendable {
    case package
    case unavailable
}

nonisolated struct BlockPropertyDefinition: Identifiable, Sendable {
    // Rows generated by one public control share an Inspector grid.
    var inspectorControlID: String? = nil
    let key: BlockProperty.Key
    let label: String
    let subtitle: String?
    let section: BlockPropertySection
    let control: BlockPropertyControl
    let defaultValue: BlockProperty.Value
    let isResponsive: Bool
    let isInspectorVisible: Bool
    let visibleWhen: BlockPackageVisibilityCondition?
    let themeValueSource: BlockPackageThemeValueSource?
    let allowsCustomThemeValue: Bool
    let supportsImageFocalPoint: Bool
    let dateMinimum: Date?
    let dateMaximum: Date?

    var id: BlockProperty.Key { key }

    init(
        key: BlockProperty.Key,
        label: String,
        subtitle: String? = nil,
        section: BlockPropertySection,
        control: BlockPropertyControl,
        defaultValue: BlockProperty.Value,
        isResponsive: Bool? = nil,
        isInspectorVisible: Bool = true,
        visibleWhen: BlockPackageVisibilityCondition? = nil,
        themeValueSource: BlockPackageThemeValueSource? = nil,
        allowsCustomThemeValue: Bool = false,
        supportsImageFocalPoint: Bool = false,
        dateMinimum: Date? = nil,
        dateMaximum: Date? = nil
    ) {
        self.key = key
        self.label = label
        self.subtitle = subtitle
        self.section = section
        self.control = control
        self.defaultValue = defaultValue
        self.isResponsive = isResponsive ?? Self.builtInResponsiveKeys.contains(key)
        self.isInspectorVisible = isInspectorVisible
        self.visibleWhen = visibleWhen
        self.themeValueSource = themeValueSource
        self.allowsCustomThemeValue = allowsCustomThemeValue
        self.supportsImageFocalPoint = supportsImageFocalPoint
        self.dateMinimum = dateMinimum
        self.dateMaximum = dateMaximum
    }

    private static let builtInResponsiveKeys: Set<BlockProperty.Key> = [
        .alignment, .padding, .backgroundColor, .textColor, .fontSize,
        .marginTop, .marginBottom, .borderColor, .borderWidth, .cornerRadius,
        .maxWidth, .horizontalAlignment, .height, .columnCount, .gap
    ]
}

nonisolated struct BlockPropertySection: RawRepresentable, Hashable, Sendable {
    let rawValue: String

    init(rawValue: String) {
        self.rawValue = rawValue
    }

    static let content = BlockPropertySection(rawValue: "Content")
    static let typography = BlockPropertySection(rawValue: "Typography")
    static let appearance = BlockPropertySection(rawValue: "Appearance")
    static let layout = BlockPropertySection(rawValue: "Layout")
    static let link = BlockPropertySection(rawValue: "Link")
    static let accessibility = BlockPropertySection(rawValue: "Accessibility")
}

nonisolated enum BlockPropertyControl: Sendable {
    indirect case array(element: BlockPropertyControl, count: Int, subtitles: [String], buttonTexts: [String], buttonIcons: [String], activeButtonTexts: [String], activeButtonIcons: [String], buttonSelectionMode: BlockPackageControl.ButtonSelectionMode, units: [String], help: String?)
    case singleLineText
    case multilineText
    case link(absoluteURL: Bool)
    case number(range: ClosedRange<Double>, step: Double, unit: String)
    case slider(range: ClosedRange<Double>, step: Double, ticks: Int, unit: String, showsValueField: Bool)
    case date
    case note(systemImage: String?)
    case button(icon: String?, text: String, activeIcon: String?, activeText: String?)
    case derived
    case color
    case colorWithOpacity
    case literalColor(allowsOpacity: Bool)
    case icon
    case packageColor(
        themeValues: Bool,
        opacity: Bool,
        initialLightShade: ColourShade? = nil,
        initialDarkShade: ColourShade? = nil
    )
    case choice([BlockPropertyChoice])
    case themeFontSize
    case themeFont
    case fontWeight(font: String?)
    case fontStyle(font: String?)
    case packageShadow
    case textAlignment
    case divider
    case toggle
    case image

    var isThemeFontSize: Bool {
        if case .themeFontSize = self { true } else { false }
    }

    var isArray: Bool {
        if case .array = self { true } else { false }
    }

}

nonisolated struct BlockPropertyChoice: Identifiable, Sendable {
    let value: String
    let label: String
    var separatorBefore: Bool = false

    var id: String { value }
}
